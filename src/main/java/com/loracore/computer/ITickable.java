package com.loracore.computer;

/**
 * Интерфейс для устройств, которые должны обновляться каждый системный тик.
 * Используется для GPU, таймеров и других устройств с внутренним состоянием.
 */
public interface ITickable {
    /**
     * Вызывается каждый системный тик.
     * @param cycles Количество системных тактов, которые нужно прожить.
     */
    void tick(long cycles);
}
